class FlowExplainer:
    def detect(self, question: str) -> Optional[dict]:
        """检测问题涉及的流程，返回步骤化结构。"""
        q = question.lower()
        best = None
        best_hits = 0
        for flow in FLOWS:
            hits = sum(1 for k in flow["keys"] if k in q)
            if hits > best_hits:
                best_hits = hits
                best = flow
        if best is None:
            return None
        return {
            "name": best["name"],
            "engine": best["engine"],
            "steps": [{"desc": d, "rule": r} for d, r in best["steps"]],
        }
